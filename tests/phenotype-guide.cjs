"use strict";
const assert = require("node:assert/strict");
require("../dist/sim-core.js"); require("../dist/phenotype-engine.js");
const C = globalThis.PrimingCore, E = globalThis.PhenotypeEngine;
const base = C.resolvePreset("sciadv", "publication"), original = JSON.stringify(base);
const protocol = {frequency:200,pulses:40,delay:.5};
const empty = () => Object.fromEntries(["first","ppr","depression","steady","recovery"].map(k => [k,{mode:"none",value:null}]));
const request = {protocol,measured:{pFusion:null,pool:null},targets:empty()};
assert.throws(() => E.compare(base,request), /at least one/);
request.targets.ppr = {mode:"same"};
const unchanged = E.compare(base,request);
assert.equal(unchanged.assessment.matched,1);
assert.deepEqual(unchanged.params,base,"No change should win when baseline satisfies observations");
assert.equal(JSON.stringify(base),original,"Baseline must never be mutated");
const synthetic = {...base,pRel0:base.pRel0*1.1,kf2:base.kf2*1.5,slope1:base.slope1*.25};
const before = E.metrics(base,protocol), after = E.metrics(synthetic,protocol);
const measured = {protocol,measured:{pFusion:1.1,pool:1},targets:Object.fromEntries(Object.keys(before).map(k => [k,{mode:"ratio",value:after[k]/before[k]}]))};
const comparison = E.compare(base,measured);
assert.equal(comparison.params.pRel0,synthetic.pRel0,"Measured pFusion is fixed");
assert.equal(comparison.params.nSites,base.nSites,"Measured N is fixed");
assert.equal(comparison.params.kRefract,base.kRefract,"b4 is fixed");
assert.equal(comparison.assessment.matched,5,"Recover observations generated by a tested mechanism");
assert.ok(comparison.assessment.rows.every(r => r.error < 1e-7));
assert.deepEqual(E.compare(base,measured).params,comparison.params,"Repeated comparisons use the same baseline");
const direction = E.assess({first:1},{first:1.3},{first:{mode:"up"}});
assert.equal(direction.rows[0].matched,true);
assert.equal(E.assess({recovery:0},{recovery:1},{recovery:{mode:"ratio",value:2}}).rows[0].matched,false,"Undefined ratios must not be successes");
const impossible = {...measured,targets:{...measured.targets,first:{mode:"ratio",value:20}}};
assert.throws(() => E.compare(base,impossible), /No candidate/);
assert.throws(() => E.compare(base,{...request,measured:{pFusion:4,pool:1}}), /probability 1/);
assert.throws(() => E.compare(base,{...request,protocol:{...protocol,pulses:2.5}}), /stimuli/);
assert.throws(() => E.compare(base,{...request,targets:{first:{mode:"ratio",value:null}}}), /positive target/);
console.log(`Phenotype guide passed: ${comparison.tested} candidates; fixed measurements, immutable baseline, synthetic observations and invalid-input handling.`);
